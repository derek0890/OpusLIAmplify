import Image from "next/image";
import Link from "next/link";
import { requireSuperAdmin } from "@/lib/super-admin";
import { prisma } from "@/lib/prisma";
import { deleteInstance } from "@/lib/actions/instances";

function mask(value: string | null): string {
  if (!value) return "—";
  return value.length <= 4 ? "••••" : `••••${value.slice(-4)}`;
}

export default async function SuperAdminPage() {
  await requireSuperAdmin();

  const instances = await prisma.whiteboxInstance.findMany({
    orderBy: { createdAt: "desc" },
    include: { createdBy: { select: { name: true } } },
  });

  return (
    <div>
      <div className="mb-6 flex items-center justify-between">
        <div>
          <h1 className="text-xl font-semibold text-slate-900">Whitebox Instances</h1>
          <p className="mt-1 text-sm text-slate-500">
            Generate the configuration for a new client deployment: name, logo, and
            Slack/Teams/Exchange/Google Workspace/AI credentials. Download the
            resulting .env file and follow the Whitebox Instance Playbook to stand
            up their own copy of the app.
          </p>
        </div>
        <Link
          href="/admin/super/new"
          className="shrink-0 rounded-md bg-blue-600 px-4 py-2 text-sm font-medium text-white hover:bg-blue-700"
        >
          + New Instance
        </Link>
      </div>

      {instances.length === 0 ? (
        <div className="rounded-xl border border-dashed border-slate-300 bg-white p-10 text-center text-sm text-slate-500">
          No instances yet. Click &ldquo;New Instance&rdquo; to generate your first one.
        </div>
      ) : (
        <div className="space-y-4">
          {instances.map((instance) => (
            <div
              key={instance.id}
              className="flex items-start gap-4 rounded-xl border border-slate-200 bg-white p-5"
            >
              <div className="flex h-12 w-12 shrink-0 items-center justify-center overflow-hidden rounded-lg border border-slate-200 bg-slate-50">
                {instance.logoUrl ? (
                  <Image src={instance.logoUrl} alt={`${instance.name} logo`} width={48} height={48} className="object-contain" />
                ) : (
                  <span className="text-xs text-slate-400">No logo</span>
                )}
              </div>

              <div className="flex-1">
                <div className="font-medium text-slate-900">{instance.name}</div>
                <div className="mt-1 text-xs text-slate-400">
                  Generated by {instance.createdBy.name} on{" "}
                  {instance.createdAt.toLocaleDateString()}
                </div>
                <div className="mt-2 grid grid-cols-2 gap-x-4 gap-y-1 text-xs text-slate-500 sm:grid-cols-4">
                  <span>Slack: {instance.slackBotToken || instance.slackWebhookUrl ? "configured" : "—"}</span>
                  <span>Teams: {instance.teamsClientId || instance.teamsWebhookUrl ? "configured" : "—"}</span>
                  <span>Exchange: {instance.exchangeClientId ? "configured" : "—"}</span>
                  <span>Google: {instance.googleClientEmail ? "configured" : "—"}</span>
                </div>
                <div className="mt-1 text-xs text-slate-400">
                  OpenAI key: {mask(instance.openaiApiKey)}
                </div>
              </div>

              <div className="flex shrink-0 items-center gap-2">
                <a
                  href={`/api/super/instances/${instance.id}/env`}
                  className="rounded-md border border-blue-300 px-3 py-1.5 text-xs font-medium text-blue-700 hover:bg-blue-50"
                >
                  Download .env
                </a>
                <form
                  action={async () => {
                    "use server";
                    await deleteInstance(instance.id);
                  }}
                >
                  <button className="rounded-md border border-red-300 px-3 py-1.5 text-xs font-medium text-red-600 hover:bg-red-50">
                    Delete
                  </button>
                </form>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
