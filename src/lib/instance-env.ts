import type { WhiteboxInstance } from "@prisma/client";

function line(key: string, value: string | null | undefined): string {
  return value ? `${key}="${value}"` : `# ${key}=""`;
}

/**
 * Builds the .env file for a new client deployment from what was collected
 * on the Super Admin page. SSO and APP_URL are deliberately left as
 * commented placeholders — they depend on that company's own identity
 * provider and hosting domain, which don't exist yet at generation time.
 * See the Whitebox Instance Playbook for what to fill in by hand.
 */
export function buildEnvFile(instance: WhiteboxInstance): string {
  return `# Generated by the Opus Amplify Super Admin page for "${instance.name}"
# on ${new Date().toISOString().slice(0, 10)}.
#
# This is a STARTING POINT, not a finished config. Fill in the commented
# lines below by hand — see the Whitebox Instance Playbook for exactly how.

# --- Core (fill in after you provision the database and pick a domain) ---
DATABASE_URL="file:./dev.db"
AUTH_SECRET="generate-a-random-string-for-production"
# The URL this instance will be reachable at once deployed — used to build
# links in notifications and the Teams OAuth redirect URI.
# APP_URL="https://${instance.name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}.your-hosting-domain.com"

# --- AI copy generation ---
${line("OPENAI_API_KEY", instance.openaiApiKey)}
${instance.openaiResearchModel ? line("OPENAI_RESEARCH_MODEL", instance.openaiResearchModel) : '# OPENAI_RESEARCH_MODEL="gpt-5.4-nano"'}
${instance.openaiCopyModel ? line("OPENAI_COPY_MODEL", instance.openaiCopyModel) : '# OPENAI_COPY_MODEL="gpt-5.5"'}

# --- Enterprise SSO (optional) — this company's own identity provider.
# Not collected on the Super Admin page since it's specific to how THIS
# company's IT department runs their IdP. See README "Deploying for a
# company's SSO" and fill these in once you have those details, or leave
# unset to use email/password login only.
# SSO_ISSUER="https://this-companys.okta.com"
# SSO_CLIENT_ID="..."
# SSO_CLIENT_SECRET="..."
# SSO_PROVIDER_NAME="Okta"
# INITIAL_ADMIN_EMAILS="admin@this-company.com"
# DISABLE_PASSWORD_LOGIN="false"

# --- Who may open /admin/super on THIS deployment. Leave unset (or set to
# an address nobody uses) on every client deployment — only your own
# internal copy of the app should ever have this set to a real address.
# SUPER_ADMIN_EMAIL="derekfrancis.14@gmail.com"

# --- Slack notifications ---
${line("SLACK_BOT_TOKEN", instance.slackBotToken)}
${line("SLACK_CHANNEL_NAME", instance.slackChannelName)}
${line("SLACK_WEBHOOK_URL", instance.slackWebhookUrl)}

# --- Microsoft Teams notifications ---
${line("TEAMS_CLIENT_ID", instance.teamsClientId)}
${line("TEAMS_CLIENT_SECRET", instance.teamsClientSecret)}
${line("TEAMS_TENANT_ID", instance.teamsTenantId)}
${line("TEAMS_TEAM_ID", instance.teamsTeamId)}
${line("TEAMS_CHANNEL_NAME", instance.teamsChannelName)}
${line("TEAMS_WEBHOOK_URL", instance.teamsWebhookUrl)}
# After deploying, an admin still needs to visit /admin/integrations on
# THIS instance and click "Connect Microsoft Teams" once — see the
# playbook, Step 4.

# --- Exchange / Outlook notifications (Microsoft Graph) ---
${line("EXCHANGE_TENANT_ID", instance.exchangeTenantId)}
${line("EXCHANGE_CLIENT_ID", instance.exchangeClientId)}
${line("EXCHANGE_CLIENT_SECRET", instance.exchangeClientSecret)}
${line("EXCHANGE_SENDER_EMAIL", instance.exchangeSenderEmail)}
${line("EXCHANGE_NOTIFY_RECIPIENTS", instance.exchangeNotifyRecipients)}

# --- Google Workspace Email notifications ---
${line("GOOGLE_CLIENT_EMAIL", instance.googleClientEmail)}
${line("GOOGLE_PRIVATE_KEY", instance.googlePrivateKey)}
${line("GOOGLE_WORKSPACE_SENDER_EMAIL", instance.googleWorkspaceSenderEmail)}
${line("GOOGLE_WORKSPACE_NOTIFY_RECIPIENTS", instance.googleWorkspaceNotifyRecipients)}
`;
}
